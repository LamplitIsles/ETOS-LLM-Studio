const { chromium } = require('@playwright/test');
const { isolatedContext } = require('./ui-test-context.cjs');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}), args: ['--no-sandbox'] });
  const context = await isolatedContext(browser, { viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://127.0.0.1:8091/', { waitUntil: 'domcontentloaded', timeout: 60000 });
    const mine = page.getByTestId('message-user').filter({ hasText: '看到这张风景图' });
    const theirs = page.getByTestId('message-agent').filter({ hasText: '合成图片' });
    await theirs.getByRole('button', { name: '查看图片' }).waitFor({ timeout: 60000 });
    const a = await mine.getByRole('button', { name: '查看图片' }).boundingBox();
    const b = await theirs.getByRole('button', { name: '查看图片' }).boundingBox();
    assert.ok(a && b && Math.abs(a.width - 180) < 2 && Math.abs(b.width - 180) < 2);
    assert.ok(a.x > b.x && Math.abs(a.height - 120) < 2 && Math.abs(b.height - 120) < 2, 'images use the appropriate side and dimensions');
    const image = theirs.locator('img[alt="聊天图片"]');
    await image.waitFor();
    assert.equal(await image.evaluate(node => getComputedStyle(node.parentElement).borderRadius), '12px');
    await theirs.getByRole('button', { name: '查看图片' }).click();
    const viewer = page.getByTestId('chat-image-viewer');
    await viewer.waitFor();
    await viewer.locator('img[alt="图片原图"]').first().waitFor({ timeout: 10000 });
    await page.emulateMedia({ colorScheme: 'dark' });
    await page.waitForFunction(() => { let node = document.querySelector('[data-testid="chat-image-viewer"]'); while (node) { if (getComputedStyle(node).backgroundColor === 'rgb(48, 52, 58)') return true; node = node.parentElement; } return false; });
    await page.emulateMedia({ colorScheme: 'light' });
    await page.waitForFunction(() => { let node = document.querySelector('[data-testid="chat-image-viewer"]'); while (node) { if (getComputedStyle(node).backgroundColor === 'rgb(244, 245, 247)') return true; node = node.parentElement; } return false; });
    const previous = viewer.getByRole('button', { name: '查看第 1 张图片' });
    const next = viewer.getByRole('button', { name: '查看第 2 张图片' });
    assert.equal(await next.getAttribute('aria-pressed'), 'true', 'the opened photo is selected');
    await previous.click();
    await viewer.locator('img[alt="图片原图"]').first().waitFor({ timeout: 10000 });
    assert.equal(await previous.getAttribute('aria-pressed'), 'true', 'duplicate attachment in a different message is a distinct photo');
    await next.click();
    assert.equal(await next.getAttribute('aria-pressed'), 'true', 'return to the original photo without dismissing the viewer');
    const pagerBox = await viewer.getByTestId('chat-image-pager').boundingBox();
    assert.ok(pagerBox && pagerBox.width > 200 && pagerBox.height > 100, 'pager has a usable touch area');
    const cdp = await context.newCDPSession(page);
    const y = pagerBox.y + pagerBox.height / 2, start = pagerBox.x + pagerBox.width * 0.2, end = pagerBox.x + pagerBox.width * 0.8;
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: start, y }] });
    for (let i = 1; i <= 8; i++) { await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start + (end - start) * i / 8, y }] }); await page.waitForTimeout(15); }
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await page.waitForFunction(() => document.querySelector('[aria-label="查看第 1 张图片"]')?.getAttribute('aria-pressed') === 'true', null, { timeout: 10000 });
    await cdp.detach();
    await viewer.getByRole('button', { name: '关闭图片' }).click();
    await viewer.waitFor({ state: 'hidden' });
    const trigger = theirs.getByRole('button', { name: '查看图片' });
    const target = await trigger.boundingBox();
    await page.mouse.move(target.x + 20, target.y + 20);
    await page.mouse.down();
    await page.waitForTimeout(650);
    await page.mouse.up();
    await theirs.getByRole('button', { name: '收藏表情' }).waitFor();
    assert.equal(await viewer.count(), 0, 'long press opens the menu without also opening the viewer');
    let releaseWrite, enteredWrite;
    const heldWrite = new Promise(resolve => { releaseWrite = resolve; });
    const entered = new Promise(resolve => { enteredWrite = resolve; });
    const holdFavorite = async route => { enteredWrite(); await heldWrite; await route.fallback(); };
    await context.route('**/api/stickers/favorites/image', holdFavorite);
    const favorite = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/api/stickers/favorites/image'));
    await theirs.getByRole('button', { name: '收藏表情' }).click();
    await entered;
    try {
      await page.getByRole('button', { name: '表情', exact: true }).click();
      const panelFavorite = page.getByRole('button', { name: '取消收藏 小绿' });
      await panelFavorite.waitFor({ timeout: 10000 });
      assert.equal(await panelFavorite.isDisabled(), true, 'panel favorite is disabled while a chat-image favorite is in flight');
    } finally { releaseWrite(); }
    assert.equal((await favorite).status(), 200);
    await context.unroute('**/api/stickers/favorites/image', holdFavorite);
    await page.getByRole('alert').filter({ hasText: '已收藏表情' }).waitFor();
    await page.getByRole('button', { name: '发送表情 合成图片.png' }).waitFor({ timeout: 10000 });
    await page.getByRole('button', { name: '键盘', exact: true }).click();
    const sticker = page.getByTestId('message-agent').filter({ has: page.locator('img[alt="表情图片"]') }).first();
    await sticker.getByRole('button', { name: '图片操作' }).click();
    const favoriteSticker = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/stickers/favorites');
    await sticker.getByRole('button', { name: '收藏表情' }).click();
    assert.equal((await favoriteSticker).request().postDataJSON().stickerId, 'fixture-sticker', 'existing sticker is saved by its original identity');
    let failedWrites = 0;
    await context.route('**/api/stickers/favorites/image', async route => { failedWrites++; await route.fulfill({ status: 503, body: '' }); });
    await mine.getByRole('button', { name: '图片操作' }).click();
    await mine.getByRole('button', { name: '收藏表情' }).click();
    await page.getByRole('alert').filter({ hasText: '收藏结果未确认' }).waitFor();
    await page.getByRole('button', { name: '表情', exact: true }).click();
    await page.getByRole('button', { name: '收藏', exact: true }).waitFor();
    assert.equal(failedWrites, 1, 'an uncertain favorite is not automatically replayed');
    assert.deepEqual(errors, []);
    console.log('PASS: image alignment, original viewing and chat-image favorite');
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
